export type Lang = "en" | "fr";
export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function resolveLang(setting: "auto" | Lang): Lang {
  if (setting !== "auto") return setting;
  return navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function makeT(lang: Lang): Translate {
  const strings = lang === "fr" ? fr : en;
  return (key, vars) => strings[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}

export type DurationStyle = "long" | "short" | "decimal";
export type Formats = ReturnType<typeof makeFormats>;

export function makeFormats(lang: Lang, timeFormat: "auto" | "24h" | "12h", durationStyle: DurationStyle) {
  const locale = lang === "fr" ? "fr-FR" : navigator.language.toLowerCase().startsWith("en") ? navigator.language : "en-GB";
  const hour12 =
    timeFormat === "auto" ? (new Intl.DateTimeFormat(locale, { hour: "numeric" }).resolvedOptions().hour12 ?? false) : timeFormat === "12h";
  // Dates arrive as "YYYY-MM-DD" (the user's local day); format them at noon UTC so no zone shifts the day.
  const asDate = (day: string) => new Date(`${day}T12:00:00Z`);
  const fmt = (o: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(locale, { ...o, timeZone: "UTC" });
  const shortDate = fmt({ day: "numeric", month: "short" });
  const longDate = fmt({ weekday: "long", day: "numeric", month: "long", year: "numeric" });
  const mediumDate = fmt({ day: "numeric", month: "short", year: "numeric" });
  const weekdayShort = fmt({ weekday: "short" });
  const weekdayLong = fmt({ weekday: "long" });
  const monthShort = fmt({ month: "short" });
  const monthYear = fmt({ month: "short", year: "numeric" });
  const monthYearLong = fmt({ month: "long", year: "numeric" });
  const number = new Intl.NumberFormat(locale);
  const decimal = new Intl.NumberFormat(locale, { maximumFractionDigits: 1 });
  const percent = new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: 0 });
  const hourOnly = new Intl.DateTimeFormat(locale, { hour: "numeric", hour12, timeZone: "UTC" });

  /** "2 h 30 min", "2:30" or "2.5 h", following the user's preference. */
  function duration(seconds: number, style: DurationStyle = durationStyle): string {
    const s = Math.max(0, seconds);
    if (style === "decimal") return `${decimal.format(s / 3600)} h`;
    const h = Math.floor(s / 3600);
    const m = Math.floor((s % 3600) / 60);
    if (style === "short") return `${h}:${String(m).padStart(2, "0")}`;
    if (h === 0) return m === 0 && s > 0 ? "< 1 min" : `${m} min`;
    return m ? `${number.format(h)} h ${m} min` : `${number.format(h)} h`;
  }

  return {
    locale,
    hour12,
    duration,
    /** Axis labels: whole hours ("3 h") or minutes for short spans. */
    axisDuration(seconds: number, step: number): string {
      if (step < 3600) return `${Math.round(seconds / 60)} min`;
      return `${number.format(Math.round(seconds / 3600))} h`;
    },
    number: (n: number) => number.format(n),
    percent: (n: number) => percent.format(n),
    shortDate: (day: string) => shortDate.format(asDate(day)),
    mediumDate: (day: string) => mediumDate.format(asDate(day)),
    longDate: (day: string) => longDate.format(asDate(day)),
    weekdayShort: (day: string) => weekdayShort.format(asDate(day)),
    weekdayLong: (day: string) => weekdayLong.format(asDate(day)),
    monthShort: (day: string) => monthShort.format(asDate(day)),
    monthYear: (day: string) => monthYear.format(asDate(day)),
    monthYearLong: (day: string) => monthYearLong.format(asDate(day)),
    /** Two-letter weekday for month grids ("lu", "Mo"), as in Calendar. */
    weekdayMini: (day: string) => weekdayShort.format(asDate(day)).replace(".", "").slice(0, 2),
    hour: (h: number) => hourOnly.format(new Date(Date.UTC(2000, 0, 1, h))),
    /** "5 min ago", "3 days ago" (timestamps, not days). */
    relative(t: string | Date, tr: Translate): string {
      const diff = (Date.now() - new Date(t).getTime()) / 1000;
      if (diff < 60) return tr("justNow");
      if (diff < 3600) return tr("minutesAgo", { n: Math.floor(diff / 60) });
      if (diff < 86400) return tr("hoursAgo", { n: Math.floor(diff / 3600) });
      if (diff < 30 * 86400) return tr("daysAgo", { n: Math.floor(diff / 86400) });
      return mediumDate.format(new Date(t));
    },
  };
}
